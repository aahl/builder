#!/usr/bin/env python3
"""Regenerate the vendored ESPHome protobuf definitions.

ESPHome's ``api.proto`` is written for ESPHome's own code generator: every
message carries a ``(id)`` option, fields carry ``(ifdef)``/``(fixed_vector)``
options, and all of them live in ``api_options.proto`` which in turn imports
``google/protobuf/descriptor.proto``. Stock ``protoc`` cannot compile that
without the well-known types on the include path, and generating Java for
``descriptor.proto`` would clash with the copy inside protobuf-javalite.

This script rewrites the file into plain proto3 that protoc accepts:

* drops the ``service APIConnection`` block (we speak the protocol by hand)
* drops every custom ``option (...)`` annotation
* drops inline field options such as ``[(fixed_vector) = true]``
* emits the message id table as Kotlin constants

Usage:
    python3 tools/sync_proto.py /path/to/esphome/components/api/api.proto
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PROTO_OUT = ROOT / "app/src/main/proto/api.proto"
ID_OUT = ROOT / "app/src/main/java/ng/anlo/hamitv/esp/EspMessageId.kt"

HEADER = '''syntax = "proto3";

// Generated by tools/sync_proto.py -- do not edit by hand.
// Source: ESPHome {version} esphome/components/api/api.proto
//
// Custom ESPHome options have been stripped so stock protoc can compile this
// file; the message ids they carried are emitted to EspMessageId.kt instead.

option java_package = "ng.anlo.hamitv.esp.proto";
option java_multiple_files = true;
'''

OPTION_LINE = re.compile(r"(?m)^[ \t]*option\s*\([^)]*\)\s*=.*;[ \t]*$")
FIELD_OPTIONS = re.compile(r"\s*\[[^\]]*\]\s*;")
MESSAGE_START = re.compile(r"^message\s+(\w+)\s*\{")
MESSAGE_ID = re.compile(r"^\s*option\s*\(id\)\s*=\s*(\d+)\s*;")


def strip_service(lines: list[str]) -> list[str]:
    out: list[str] = []
    depth = 0
    skipping = False
    for line in lines:
        if not skipping and line.lstrip().startswith("service "):
            skipping = True
            depth = line.count("{") - line.count("}")
            if depth <= 0:
                skipping = False
            continue
        if skipping:
            depth += line.count("{") - line.count("}")
            if depth <= 0:
                skipping = False
            continue
        out.append(line)
    return out


def collect_ids(lines: list[str]) -> list[tuple[str, int]]:
    ids: list[tuple[str, int]] = []
    current: str | None = None
    for line in lines:
        start = MESSAGE_START.match(line)
        if start:
            current = start.group(1)
            continue
        if current:
            found = MESSAGE_ID.match(line)
            if found:
                ids.append((current, int(found.group(1))))
                current = None
    return ids


def transform(source: str) -> str:
    lines = [line for line in source.splitlines() if not line.lstrip().startswith("import ")]
    lines = strip_service(lines)

    text = "\n".join(lines)
    text = OPTION_LINE.sub("", text)
    # field options may span several lines, so collapse them on the whole text
    text = FIELD_OPTIONS.sub(";", text)

    # drop the original syntax line, it is re-emitted in the header
    text = re.sub(r"^syntax\s*=\s*\"proto3\";\s*", "", text.lstrip("\n"))
    return text


def to_snake(name: str) -> str:
    """HelloRequest -> HELLO_REQUEST"""
    out = re.sub(r"(?<!^)(?=[A-Z])", "_", name)
    return out.upper()


def kotlin_ids(ids: list[tuple[str, int]], version: str) -> str:
    entries = "\n".join(
        f"    const val {to_snake(name)} = {value}" for name, value in ids
    )
    mapping = "\n".join(
        f'        {value} to "{name}",' for name, value in ids
    )
    return f'''package ng.anlo.hamitv.esp

/**
 * ESPHome API message ids, generated by tools/sync_proto.py.
 *
 * Source: ESPHome {version} api.proto
 */
object EspMessageId {{
{entries}

    private val names = mapOf(
{mapping}
    )

    fun name(id: Int): String = names[id] ?: "unknown($id)"
}}
'''


def main() -> int:
    if len(sys.argv) != 2:
        print(__doc__)
        return 1

    src = Path(sys.argv[1])
    source = src.read_text(encoding="utf-8")
    version = sys.argv[1].split("/esphome/")[0].split("-")[-1] if "/esphome/" in sys.argv[1] else "unknown"

    ids = collect_ids(source.splitlines())
    if not ids:
        print("no message ids found, wrong file?", file=sys.stderr)
        return 1

    PROTO_OUT.write_text(HEADER.format(version=version) + transform(source), encoding="utf-8")
    ID_OUT.write_text(kotlin_ids(ids, version), encoding="utf-8")
    print(f"wrote {PROTO_OUT} ({len(ids)} message ids)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
